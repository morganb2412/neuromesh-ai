class PostgresConnection:
    """Minimal adapter for the controlled SQL used by this service."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql: str, params=()):
        return self.connection.execute(sql.replace('?', '%s'), params)

    def executescript(self, script: str):
        for statement in script.split(';'):
            if statement.strip():
                self.connection.execute(statement)

    def commit(self):
        self.connection.commit()

    def close(self):
        self.connection.close()


def is_postgres() -> bool:
    return bool(os.getenv('NEUROMESH_DATABASE_URL') or os.getenv('NEUROMESH_DB_HOST'))


def db_path() -> Path:
    return Path(os.getenv('NEUROMESH_DB', str(Path(__file__).resolve().parents[3] / 'data' / 'neuromesh.db')))


@contextmanager
def connect():
    if is_postgres():
        import psycopg
        from psycopg.rows import dict_row
        if os.getenv('NEUROMESH_DATABASE_URL'):
            connection = psycopg.connect(os.environ['NEUROMESH_DATABASE_URL'], row_factory=dict_row, connect_timeout=5)
        else:
            connection = psycopg.connect(
                host=os.environ['NEUROMESH_DB_HOST'],
                dbname=os.environ['NEUROMESH_DB_NAME'],
                user=os.environ['NEUROMESH_DB_USER'],
                password=os.environ['NEUROMESH_DB_PASSWORD'],
                row_factory=dict_row, connect_timeout=5,
            )
        db = PostgresConnection(connection)
    else:
        path = db_path()
        path.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(path)
        db.row_factory = sqlite3.Row
        db.execute('PRAGMA foreign_keys=ON')
    try:
        yield db
        db.commit()
    finally:
        db.close()


def initialize():
    with connect() as db:
        db.executescript(SCHEMA_POSTGRES if is_postgres() else SCHEMA)


def reserve_usage(kind: str, units: int, daily_limit: int) -> bool:
    """Reserve a bounded paid operation before calling its provider."""
    with connect() as db:
        if is_postgres():
            db.execute('SELECT pg_advisory_xact_lock(hashtext(?))', (f'neuromesh:{kind}',))
        else:
            db.execute('BEGIN IMMEDIATE')
        used = db.execute('SELECT COALESCE(SUM(units),0) AS n FROM usage_events WHERE kind=? AND created_at>=CURRENT_DATE', (kind,)).fetchone()['n']
        if used + units > daily_limit:
            return False
        db.execute('INSERT INTO usage_events(id,kind,units) VALUES(?,?,?)', (str(uuid.uuid4()),kind,units))
    return True


def graph():
    with connect() as db:
        nodes = [dict(row) for row in db.execute('SELECT id,label,kind,description,demo,source_record_id FROM entities')]
        edges = [dict(row) for row in db.execute('SELECT id,source_id,target_id,kind,confidence,evidence_id,demo FROM relationships')]
        evidence = {row['id']: dict(row) for row in db.execute('SELECT id,source_record_id,excerpt,url FROM evidence')}
    return {'nodes': nodes, 'edges': edges, 'evidence': evidence, 'mode': 'live' if any(not n['demo'] for n in nodes) else 'demo'}


def status():
    with connect() as db:
        counts = {name: db.execute(f'SELECT COUNT(*) AS n FROM {name}').fetchone()['n'] for name in ('entities','relationships','source_records','evidence')}
        jobs = [dict(r) for r in db.execute('SELECT * FROM ingestion_jobs ORDER BY id DESC LIMIT 12')]
        sources = [dict(r) for r in db.execute('SELECT source,COUNT(*) AS records,MAX(retrieved_at) AS last_sync FROM source_records GROUP BY source')]
    return {'counts': counts, 'jobs': jobs, 'sources': sources,
            'configured_adk': bool(os.getenv('NEUROMESH_ENABLE_ADK') == 'true' and os.getenv('NEUROMESH_MODEL')),
            'configured_tts': os.getenv('NEUROMESH_ENABLE_CLOUD_TTS') == 'true',
            'mode': 'live' if counts['source_records'] else 'demo'}
